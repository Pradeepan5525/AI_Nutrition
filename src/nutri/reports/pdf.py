"""PDF Report Generator for AI Nutrition Intelligence System.

Generates professional, publication-quality 2-page clinical health summaries,
risk assessments, personalized meal plans, and grocery shopping lists using ReportLab.
Strictly incorporates medical disclaimers and clinical audit notes.
"""

from __future__ import annotations

import io
from datetime import datetime
from typing import Any, Dict

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

MEDICAL_DISCLAIMER_TEXT = (
    "<b>IMPORTANT MEDICAL & CLINICAL DISCLAIMER:</b> This report is generated by an artificial "
    "intelligence research and clinical-rule system for educational and informational purposes only. "
    "It does not constitute medical advice, diagnosis, or treatment. Nutrition recommendations and "
    "lifestyle risk models must not supersede personalized clinical judgment. Individuals with chronic "
    "conditions, eating disorders, or pregnancy should consult a registered dietitian or licensed physician."
)


def _build_styles() -> Dict[str, ParagraphStyle]:
    """Construct a clean, professional typography palette."""
    base_styles = getSampleStyleSheet()
    styles = {}

    styles["Title"] = ParagraphStyle(
        "DocTitle",
        parent=base_styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),  # Slate 900
    )
    styles["Subtitle"] = ParagraphStyle(
        "DocSubtitle",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#64748b"),  # Slate 500
    )
    styles["Heading"] = ParagraphStyle(
        "SectionHeading",
        parent=base_styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=4,
    )
    styles["Body"] = ParagraphStyle(
        "BodyDark",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#334155"),
    )
    styles["BodyBold"] = ParagraphStyle(
        "BodyDarkBold",
        parent=styles["Body"],
        fontName="Helvetica-Bold",
    )
    styles["Disclaimer"] = ParagraphStyle(
        "DisclaimerText",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor("#991b1b"),  # Red 800
    )
    styles["TableHeader"] = ParagraphStyle(
        "TableHeader",
        parent=base_styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0f172a"),
    )
    styles["TableCell"] = ParagraphStyle(
        "TableCell",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=7.5,
        leading=9.5,
        textColor=colors.HexColor("#334155"),
    )
    styles["BadgeSafe"] = ParagraphStyle(
        "BadgeSafe",
        parent=styles["TableCell"],
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#166534"),
    )
    styles["BadgeWarn"] = ParagraphStyle(
        "BadgeWarn",
        parent=styles["TableCell"],
        fontName="Helvetica-Bold",
        textColor=colors.HexColor("#b45309"),
    )
    return styles


def generate_nutrition_pdf(data: Dict[str, Any]) -> bytes:
    """Generate a high-density, multi-section clinical nutrition PDF report.

    Args:
        data: Dict containing:
            - client_info (age, sex, height_cm, weight_kg, bmi, bmi_category, tdee, goal)
            - target_nutrition (target_kcal, protein_g, fat_g, carbs_g, fiber_g, sugar_g, water_ml)
            - safety_gate (cleared, flags)
            - clinical_rules (active_rules, citations)
            - risk_screening (predicted_category, probabilities, top_risks, top_protective)
            - meal_plan (daily_plans with meals)
            - grocery_list (by department)
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=36,
    )
    styles = _build_styles()
    story = []

    # 1. Header
    report_date = datetime.now().strftime("%B %d, %Y - %H:%M UTC")
    header_data = [
        [
            Paragraph("<b>AI Nutrition Intelligence System</b>", styles["Title"]),
            Paragraph(f"<b>Clinical Summary Report</b><br/>{report_date}", styles["Subtitle"]),
        ]
    ]
    header_table = Table(header_data, colWidths=[360, 180])
    header_table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("ALIGN", (1, 0), (1, 0), "RIGHT"),
            ]
        )
    )
    story.append(header_table)
    story.append(Spacer(1, 6))

    # 2. Prominent Disclaimer Box
    disclaimer_p = Paragraph(MEDICAL_DISCLAIMER_TEXT, styles["Disclaimer"])
    disclaimer_box = Table([[disclaimer_p]], colWidths=[540])
    disclaimer_box.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fef2f2")),  # Light red tint
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#f87171")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    story.append(disclaimer_box)
    story.append(Spacer(1, 10))

    # 3. Assessment & Metabolic Energy Summary
    story.append(Paragraph("1. Anthropometric & Metabolic Assessment", styles["Heading"]))
    client = data.get("client_info") or {}
    target = data.get("target_nutrition") or {}

    age = client.get("age", "N/A")
    sex = client.get("sex", "N/A")
    height = f"{client.get('height_cm', 'N/A')} cm"
    weight = f"{client.get('weight_kg', 'N/A')} kg"
    bmi = client.get("bmi", "N/A")
    bmi_cat = client.get("bmi_category", "N/A")
    bmr = f"{client.get('bmr', 'N/A')} kcal"
    tdee = f"{client.get('tdee', 'N/A')} kcal"
    goal_kcal = f"{target.get('target_kcal', 'N/A')} kcal"

    assess_data = [
        [
            Paragraph("<b>Age / Sex:</b>", styles["TableCell"]),
            Paragraph(f"{age} y / {sex}", styles["TableCell"]),
            Paragraph("<b>Height / Weight:</b>", styles["TableCell"]),
            Paragraph(f"{height} / {weight}", styles["TableCell"]),
            Paragraph("<b>BMI:</b>", styles["TableCell"]),
            Paragraph(f"{bmi} ({bmi_cat})", styles["TableCell"]),
        ],
        [
            Paragraph("<b>BMR (Mifflin-St Jeor):</b>", styles["TableCell"]),
            Paragraph(str(bmr), styles["TableCell"]),
            Paragraph("<b>Maintenance TDEE:</b>", styles["TableCell"]),
            Paragraph(str(tdee), styles["TableCell"]),
            Paragraph("<b>Target Energy:</b>", styles["TableCell"]),
            Paragraph(f"<b>{goal_kcal}</b>", styles["TableCell"]),
        ],
        [
            Paragraph("<b>Protein Target:</b>", styles["TableCell"]),
            Paragraph(f"{target.get('protein_g', 'N/A')} g", styles["TableCell"]),
            Paragraph("<b>Carbohydrates:</b>", styles["TableCell"]),
            Paragraph(f"{target.get('carbs_g', 'N/A')} g", styles["TableCell"]),
            Paragraph("<b>Fat Target:</b>", styles["TableCell"]),
            Paragraph(f"{target.get('fat_g', 'N/A')} g", styles["TableCell"]),
        ],
        [
            Paragraph("<b>Dietary Fiber:</b>", styles["TableCell"]),
            Paragraph(f"{target.get('fiber_g', 'N/A')} g", styles["TableCell"]),
            Paragraph("<b>Added Sugar Cap:</b>", styles["TableCell"]),
            Paragraph(f"≤ {target.get('sugar_g', 'N/A')} g", styles["TableCell"]),
            Paragraph("<b>Hydration Guide:</b>", styles["TableCell"]),
            Paragraph(f"{target.get('water_ml', 'N/A')} mL", styles["TableCell"]),
        ],
    ]
    assess_table = Table(assess_data, colWidths=[90, 90, 95, 85, 90, 90])
    assess_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(assess_table)
    story.append(Spacer(1, 10))

    # 4. Clinical Safety Gate & Guideline Constraints
    story.append(Paragraph("2. Clinical Safety Evaluation & Clinical Rules", styles["Heading"]))
    safety = data.get("safety_gate") or {}
    cleared = safety.get("cleared", True)
    flags = safety.get("flags", [])
    clinical_rules_dict = data.get("clinical_rules") or {}
    rules = clinical_rules_dict.get("active_rules", [])

    safety_status = (
        Paragraph("✓ Cleared for Automated Dietary Planning", styles["BadgeSafe"])
        if cleared
        else Paragraph(
            "⚠ Safety Gate Flagged (Clinical Consultation Recommended)", styles["BadgeWarn"]
        )
    )
    flag_desc = ", ".join(flags) if flags else "None detected."
    rule_desc = (
        ", ".join(rules)
        if rules
        else "General Dietary Guidelines (AHA/Dietary Guidelines for Americans)."
    )

    clinical_data = [
        [Paragraph("<b>Safety Screening:</b>", styles["TableCell"]), safety_status],
        [
            Paragraph("<b>Identified Clinical Flags:</b>", styles["TableCell"]),
            Paragraph(flag_desc, styles["TableCell"]),
        ],
        [
            Paragraph("<b>Active Evidence Guidelines:</b>", styles["TableCell"]),
            Paragraph(rule_desc, styles["TableCell"]),
        ],
    ]
    clinical_table = Table(clinical_data, colWidths=[130, 410])
    clinical_table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(clinical_table)
    story.append(Spacer(1, 10))

    # 5. Lifestyle Risk Screening & SHAP Drivers
    risk = data.get("risk_screening") or {}
    if risk:
        story.append(Paragraph("3. Multi-Factor Lifestyle Risk Assessment", styles["Heading"]))
        pred_cat = risk.get("predicted_category", "N/A")
        probs = risk.get("probabilities", {})
        top_risks = risk.get("top_risks", [])
        top_prot = risk.get("top_protective", [])

        prob_str = (
            " | ".join([f"{k}: {v * 100:.1f}%" for k, v in probs.items()]) if probs else "N/A"
        )
        risk_drivers_str = "; ".join(top_risks) if top_risks else "None dominant"
        prot_str = "; ".join(top_prot) if top_prot else "None dominant"

        risk_data = [
            [
                Paragraph("<b>Predicted Lifestyle Tier:</b>", styles["TableCell"]),
                Paragraph(f"<b>{pred_cat}</b>", styles["TableCell"]),
            ],
            [
                Paragraph("<b>Calibrated Probabilities:</b>", styles["TableCell"]),
                Paragraph(prob_str, styles["TableCell"]),
            ],
            [
                Paragraph("<b>Top Risk Drivers (SHAP):</b>", styles["TableCell"]),
                Paragraph(risk_drivers_str, styles["TableCell"]),
            ],
            [
                Paragraph("<b>Top Protective Factors:</b>", styles["TableCell"]),
                Paragraph(prot_str, styles["TableCell"]),
            ],
        ]
        risk_table = Table(risk_data, colWidths=[130, 410])
        risk_table.setStyle(
            TableStyle(
                [
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 6),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ]
            )
        )
        story.append(risk_table)
        story.append(Spacer(1, 10))

    # Page Break for Meal Plan & Grocery Section
    story.append(PageBreak())

    # 6. Optimized Meal Plan
    story.append(Paragraph("4. Personalized Optimized Meal Schedule", styles["Heading"]))
    meal_plan = data.get("meal_plan") or {}
    daily_plans = meal_plan.get("daily_plans", [])

    if daily_plans:
        # Display Day 1 detailed schedule
        day1 = daily_plans[0]
        meals = day1.get("meals", {})
        totals = day1.get("daily_totals", {})

        plan_headers = [
            Paragraph("<b>Meal Slot</b>", styles["TableHeader"]),
            Paragraph("<b>Food Item</b>", styles["TableHeader"]),
            Paragraph("<b>Portion</b>", styles["TableHeader"]),
            Paragraph("<b>Energy</b>", styles["TableHeader"]),
            Paragraph("<b>Protein</b>", styles["TableHeader"]),
            Paragraph("<b>Carbs</b>", styles["TableHeader"]),
            Paragraph("<b>Fat</b>", styles["TableHeader"]),
            Paragraph("<b>Sodium</b>", styles["TableHeader"]),
        ]
        plan_rows = [plan_headers]

        for slot_name in ["breakfast", "lunch", "dinner", "snack"]:
            slot_items = meals.get(slot_name, [])
            for i, item in enumerate(slot_items):
                slot_label = slot_name.capitalize() if i == 0 else ""
                plan_rows.append(
                    [
                        Paragraph(f"<b>{slot_label}</b>", styles["TableCell"]),
                        Paragraph(str(item.get("name", "Item")), styles["TableCell"]),
                        Paragraph(f"{item.get('portion_g', 0):.0f}g", styles["TableCell"]),
                        Paragraph(f"{item.get('kcal', 0):.0f} kcal", styles["TableCell"]),
                        Paragraph(f"{item.get('protein_g', 0):.1f}g", styles["TableCell"]),
                        Paragraph(f"{item.get('carbs_g', 0):.1f}g", styles["TableCell"]),
                        Paragraph(f"{item.get('fat_g', 0):.1f}g", styles["TableCell"]),
                        Paragraph(f"{item.get('sodium_mg', 0):.0f}mg", styles["TableCell"]),
                    ]
                )

        # Summary total row
        plan_rows.append(
            [
                Paragraph("<b>TOTALS</b>", styles["TableHeader"]),
                Paragraph("<b>Day 1 Sum</b>", styles["TableHeader"]),
                Paragraph("-", styles["TableHeader"]),
                Paragraph(f"<b>{totals.get('kcal', 0):.0f} kcal</b>", styles["TableHeader"]),
                Paragraph(f"<b>{totals.get('protein_g', 0):.1f}g</b>", styles["TableHeader"]),
                Paragraph(f"<b>{totals.get('carbs_g', 0):.1f}g</b>", styles["TableHeader"]),
                Paragraph(f"<b>{totals.get('fat_g', 0):.1f}g</b>", styles["TableHeader"]),
                Paragraph(f"<b>{totals.get('sodium_mg', 0):.0f}mg</b>", styles["TableHeader"]),
            ]
        )

        plan_table = Table(plan_rows, colWidths=[65, 175, 45, 55, 50, 50, 50, 50])
        plan_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                    ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#e2e8f0")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(plan_table)
    else:
        story.append(Paragraph("<i>No meal plan generated in this session.</i>", styles["Body"]))

    story.append(Spacer(1, 10))

    # 7. Department-Categorized Grocery List
    story.append(Paragraph("5. Consolidated Grocery & Pantry List", styles["Heading"]))
    grocery = data.get("grocery_list") or {}
    items_by_dept = (grocery.get("items_by_department") or grocery.get("departments")) or {}
    if items_by_dept:
        grocery_rows = [
            [
                Paragraph("<b>Department</b>", styles["TableHeader"]),
                Paragraph("<b>Items & Estimated Total Purchase Weight</b>", styles["TableHeader"]),
            ]
        ]
        for dept, items in items_by_dept.items():
            item_summaries = [f"{it['name']} ({it['total_weight_g']:.0f}g)" for it in items]
            grocery_rows.append(
                [
                    Paragraph(f"<b>{dept}</b>", styles["TableCell"]),
                    Paragraph(", ".join(item_summaries), styles["TableCell"]),
                ]
            )

        grocery_table = Table(grocery_rows, colWidths=[110, 430])
        grocery_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 5),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(grocery_table)
    else:
        story.append(Paragraph("<i>No grocery items specified.</i>", styles["Body"]))

    story.append(Spacer(1, 12))
    story.append(
        HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#94a3b8"), spaceAfter=5)
    )
    story.append(
        Paragraph(
            "AI Nutrition Intelligence System • Algorithmic Optimization via PuLP MILP • Clinical Rules v2.1 • Confidential Medical Summary",
            styles["Subtitle"],
        )
    )

    # Build the document
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


def save_nutrition_pdf(data: Dict[str, Any], filepath: str) -> None:
    """Helper function to write generated PDF to a disk filepath."""
    pdf_bytes = generate_nutrition_pdf(data)
    with open(filepath, "wb") as f:
        f.write(pdf_bytes)
